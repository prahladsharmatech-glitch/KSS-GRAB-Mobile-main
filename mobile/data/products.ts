export function getProductById(id: string | number): CatalogProduct | undefined {
  const strId = String(id).toLowerCase().trim();
  return products.find(p => String(p.id).toLowerCase() === strId || String(p.sku || '').toLowerCase() === strId);
}

export function getProductsByCategory(categorySlug: string): CatalogProduct[] {
  if (!categorySlug || categorySlug === 'all') return products;
  const canonical = getCanonicalSlug(categorySlug);
  return products.filter(p => getCanonicalSlug(p.category) === canonical || getCanonicalSlug(p.category_slug || '') === canonical);
}

export function searchProducts(query: string): CatalogProduct[] {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();
  return products.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    (p.brand && p.brand.toLowerCase().includes(q))
  );
}

